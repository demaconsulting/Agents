# --- TEXTLINT SECTION ---
# Restores dotnet tools and runs TextLint (files are configured in .textlint.yaml).
Write-Host "Linting: spelling..."
dotnet tool restore
$skipDotnetTools = $LASTEXITCODE -ne 0
if ($skipDotnetTools) { $lintError = $true }
else {
    dotnet textlint
    if ($LASTEXITCODE -ne 0) { $lintError = $true }
}

# --- MARKDOWN SECTION ---
# Runs LintMark with the tools restored above (files are configured in .lintmark.yaml).
Write-Host "Linting: markdown..."
if (-not $skipDotnetTools) {
    dotnet lintmark
    if ($LASTEXITCODE -ne 0) { $lintError = $true }
}

